/**
 * docs/api-reference.md, rendered from the server's own OpenAPI document.
 *
 * The page was written by hand once and then described an API a few hundred
 * routes smaller than the one being served. Rendering it from the route table
 * means a new route appears the next time it is generated, with the summary its
 * schema already carries, and serverBoot.test.ts fails while the stored page
 * differs from what the routes would render.
 *
 * Pure: the caller builds the server and hands over `app.swagger()`.
 */

const METHOD_ORDER = ['get', 'post', 'put', 'patch', 'delete'] as const

/** Repository-relative path of the generated page. */
export const API_REFERENCE_PATH = 'docs/api-reference.md'

interface Operation {
  summary?: string
  tags?: string[]
}

interface OpenApiDocument {
  tags?: { name: string; description?: string }[]
  paths: Record<string, Partial<Record<string, Operation>>>
}

function cell(text: string): string {
  return text.replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim()
}

/**
 * Tags are grouped case-insensitively: a route tagged 'Settings' beside the
 * document's 'settings' is one area, not a second section whose heading
 * collides with the first one's anchor.
 */
function tagKey(tag: string): string {
  return tag.trim().toLowerCase()
}

/** A route whose schema names no tag is filed under its first path segment. */
function areaOf(path: string): string {
  const parts = path.split('/').filter(Boolean)
  return (parts[0] === 'api' ? parts[1] : parts[0]) ?? 'other'
}

/**
 * GitHub's heading anchor. A copy of `githubSlug` in
 * apps/web/src/components/docs/markdown.ts, which the API cannot import; the
 * two must agree, or a Contents link lands nowhere.
 */
function githubSlug(text: string): string {
  return text
    .trim()
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\p{M} _-]/gu, '')
    .replace(/ /g, '-')
}

export function renderApiReference(spec: OpenApiDocument): { markdown: string; total: number; sections: number } {
  const tagInfo = new Map<string, string>()
  for (const tag of spec.tags ?? []) {
    const key = tagKey(tag.name)
    if (!tagInfo.has(key)) tagInfo.set(key, tag.description ?? '')
  }

  // One section per tag in the document's own order, then any tag a route uses
  // that the document does not describe, then each untagged route's area.
  const groups = new Map<string, { method: string; path: string; op: Operation }[]>()
  for (const key of tagInfo.keys()) groups.set(key, [])

  let total = 0
  for (const path of Object.keys(spec.paths).sort()) {
    const item = spec.paths[path]
    for (const method of METHOD_ORDER) {
      const op = item[method]
      if (!op) continue
      total++
      const key = tagKey(op.tags?.[0] ?? areaOf(path))
      if (!groups.has(key)) groups.set(key, [])
      groups.get(key)!.push({ method, path, op })
    }
  }

  const sections = [...groups.entries()].filter(([, routes]) => routes.length > 0)

  const lines: string[] = []
  lines.push('# API Reference')
  lines.push('')
  lines.push(
    "<!-- Generated by apps/api/scripts/api-reference.ts from the server's OpenAPI document. Do not edit by hand: run `pnpm --filter @aperture/api docs:api`. serverBoot.test.ts fails while this page is out of date. -->",
  )
  lines.push('')
  lines.push(
    `Every endpoint the API serves, ${total} in all, grouped by area. The running server documents each one with its request and response schemas, and lets you try them, at **\`/openapi\`** (admin-only in production; see \`API_DOCS\` in [Configuration](configuration.md)).`,
  )
  lines.push('')
  lines.push(
    'Requests authenticate with the `aperture_session` cookie or an `X-API-Key` header. Every route declares who may call it: most need a signed-in user, admin routes need an admin, and per-feature routes need that feature switched on for the account. An API key is limited to the scopes it was given (`read`, `write`, `admin`; see [API keys](admin/api-keys.md)). The routes that answer without a session (health checks, login, the setup wizard before setup completes, branding, the newsletter unsubscribe link and a few more) are listed with their reasons in `apps/api/src/routes/routeGuards.test.ts`.',
  )
  lines.push('')
  lines.push('## Contents')
  lines.push('')
  for (const [name, routes] of sections) lines.push(`- [${name}](#${githubSlug(name)}) (${routes.length})`)
  lines.push('')

  for (const [name, routes] of sections) {
    lines.push('---')
    lines.push('')
    lines.push(`## ${name}`)
    lines.push('')
    const description = tagInfo.get(name)
    if (description) {
      lines.push(cell(description))
      lines.push('')
    }
    lines.push('| Method | Path | Summary |')
    lines.push('| ------ | ---- | ------- |')
    for (const { method, path, op } of routes) {
      lines.push(`| ${method.toUpperCase()} | \`${path}\` | ${cell(op.summary ?? '') || '—'} |`)
    }
    lines.push('')
  }

  return { markdown: lines.join('\n'), total, sections: sections.length }
}
